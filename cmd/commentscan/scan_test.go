func writeTree(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for name, body := range files {
		path := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func TestWalkReportsEveryFileWithAComment(t *testing.T) {
	root := writeTree(t, map[string]string{
		"clean.go":          "package a\n",
		"sub/noisy.go":      "package b\n\n// note\nvar x = 1\n",
		"sub/noisy_test.go": "package b\n\nvar y = 1 // note\n",
	})
	findings, err := Walk(root)
	if err != nil {
		t.Fatal(err)
	}
	got := map[string][]int{}
	for _, f := range findings {
		rel, _ := filepath.Rel(root, f.File)
		got[rel] = append(got[rel], f.Line)
	}
	want := map[string][]int{"sub/noisy.go": {3}, "sub/noisy_test.go": {3}}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("want %v, got %v", want, got)
	}
}

func TestWalkSkipsTestdataAndHiddenDirectories(t *testing.T) {
	root := writeTree(t, map[string]string{
		"testdata/sample.go": "package a\n\n// note\nvar x = 1\n",
		".git/hooks/x.go":    "package a\n\n// note\nvar x = 1\n",
		"real.go":            "package a\n",
	})
	findings, err := Walk(root)
	if err != nil {
		t.Fatal(err)
	}
	if len(findings) != 0 {
		t.Fatalf("testdata and hidden directories are skipped, got %v", findings)
	}
}

