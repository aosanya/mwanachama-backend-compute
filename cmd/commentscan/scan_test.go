func lines(findings []Finding) []int {
	out := make([]int, 0, len(findings))
	for _, f := range findings {
		out = append(out, f.Line)
	}
	return out
}

func TestSourceWithoutCommentsHasNoFindings(t *testing.T) {
	src := "package sample\n\nfunc Total(a, b int) int {\n\treturn a + b\n}\n"
	findings, err := Scan("sample.go", []byte(src))
	if err != nil {
		t.Fatal(err)
	}
	if len(findings) != 0 {
		t.Fatalf("want none, got %v", findings)
	}
}

func TestEachKindOfCommentIsFound(t *testing.T) {
	cases := []struct {
		name string
		src  string
		want []int
	}{
		{"line comment above a function", "package sample\n\n// Total adds.\nfunc Total() {}\n", []int{3}},
		{"trailing comment", "package sample\n\nvar x = 1 // one\n", []int{3}},
		{"block comment", "package sample\n\n/* note */\nvar x = 1\n", []int{3}},
		{"comment inside a body", "package sample\n\nfunc F() {\n\t// step\n\t_ = 1\n}\n", []int{4}},
		{"two separate comments", "package sample\n\n// a\nvar x = 1\n\n// b\nvar y = 2\n", []int{3, 6}},
		{"a multi line group reports each line", "package sample\n\n// a\n// b\nvar x = 1\n", []int{3, 4}},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			findings, err := Scan("sample.go", []byte(c.src))
			if err != nil {
				t.Fatal(err)
			}
			if got := lines(findings); !reflect.DeepEqual(got, c.want) {
				t.Fatalf("want lines %v, got %v", c.want, got)
			}
		})
	}
}

